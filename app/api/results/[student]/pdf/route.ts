import { requestClientOrNull } from "@/lib/supabase/request-client";
import { withAuth } from "@/lib/auth/api-guard";
import { NextResponse } from "next/server";
import { apiError } from "@/lib/http";
import PDFDocument from "pdfkit";
import path from "path";
import fs from "fs";
import { getLiveResultByStudent, getPrimaryOrganization, hasPortalLink } from "@/lib/supabase/school-data";

type RouteParams = { params: Promise<{ student: string }> };


export const runtime = "nodejs";

type SubjectRow = {
  ca_score?: number | string;
  exam_score?: number | string;
  total_score?: number | string;
  grade?: string | null;
  remark?: string | null;
  term?: string | null;
  session?: string | null;
  teacher_comment?: string | null;
  principal_comment?: string | null;
  subjects?: { name?: string } | null;
};

function grade(score: number) {
  if (score >= 80) return ["A", "Excellent"];
  if (score >= 70) return ["B", "Very Good"];
  if (score >= 60) return ["C", "Good"];
  if (score >= 50) return ["D", "Fair"];
  return ["F", "Needs Improvement"];
}

function getLogoPath() {
  const candidates = [
    path.join(process.cwd(), "public/brand/Horizons-site-logo.png"),
    path.join(process.cwd(), "public/icon-192.png"),
  ];
  return candidates.find((candidate) => fs.existsSync(candidate));
}

export const GET = withAuth<RouteParams>("results.view", async (_request: Request, context, { params }) => {
  const { student } = await params;
  const supabase = await requestClientOrNull();
  if (!supabase) return NextResponse.json({ status: "not_configured", message: "Database is not configured." }, { status: 503 });

  // Portal accounts download only linked students; staff keep school-wide access.
  if (!await hasPortalLink(supabase, context.user.email, context.role, student)) {
    return NextResponse.json({ status: "error", code: "forbidden", message: "This record is not linked to your account." }, { status: 403 });
  }

  try {
    const bundle = await getLiveResultByStudent(supabase, student.toUpperCase());
    if (!bundle || !bundle.results.length) return NextResponse.json({ status: "not_found", message: "No result records found for this student." }, { status: 404 });
    const organization = await getPrimaryOrganization(supabase);
    const studentRow = bundle.student;
    const results = bundle.results as SubjectRow[];
    const total = results.reduce((sum, row) => sum + Number(row.total_score ?? 0), 0);
    const average = Math.round(total / results.length);
    const [overallGrade, overallRemark] = grade(average);
    const term = String(results[0]?.term ?? "Term");
    const session = String(results[0]?.session ?? "Session");

    const doc = new PDFDocument({ size: "A4", margin: 42, info: { Title: `Report Card - ${studentRow.admission_no}`, Author: "Horizons" } });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk) => chunks.push(Buffer.from(chunk)));

    const logo = getLogoPath();
    if (logo) doc.image(logo, 42, 28, { width: 170 });
    doc.fontSize(10).fillColor("#64748B").text("Generated by Horizons", 380, 42, { align: "right", width: 170 });
    doc.moveDown(3.2);

    doc.fillColor("#07111F").fontSize(24).font("Helvetica-Bold").text(organization?.name ?? "School Academic Report", 42, 112);
    doc.fontSize(11).font("Helvetica").fillColor("#475569").text(`Academic Report Card • ${term} • ${session}`, 42, 142);
    doc.moveTo(42, 166).lineTo(553, 166).strokeColor("#E2E8F0").stroke();

    const studentName = `${studentRow.first_name ?? ""} ${studentRow.last_name ?? ""}`.trim();
    const infoY = 188;
    const info = [
      ["Student", studentName],
      ["Admission No.", studentRow.admission_no],
      ["Overall Average", `${average}%`],
      ["Overall Grade", `${overallGrade} • ${overallRemark}`],
    ];
    info.forEach(([label, value], index) => {
      const x = 42 + (index % 2) * 255;
      const y = infoY + Math.floor(index / 2) * 54;
      doc.roundedRect(x, y, 238, 42, 8).fillAndStroke("#F8FAFC", "#E2E8F0");
      doc.fillColor("#64748B").fontSize(8).font("Helvetica-Bold").text(label.toUpperCase(), x + 12, y + 8);
      doc.fillColor("#0F172A").fontSize(12).font("Helvetica-Bold").text(String(value), x + 12, y + 22, { width: 210 });
    });

    const tableY = 320;
    doc.fillColor("#0F172A").fontSize(15).font("Helvetica-Bold").text("Subject Performance", 42, tableY - 28);
    const columns = [42, 210, 260, 312, 370, 420];
    const headers = ["Subject", "CA", "Exam", "Total", "Grade", "Remark"];
    doc.roundedRect(42, tableY, 511, 28, 8).fill("#07111F");
    headers.forEach((header, index) => doc.fillColor("#FFFFFF").fontSize(9).font("Helvetica-Bold").text(header, columns[index] + 6, tableY + 10));
    let y = tableY + 34;
    results.forEach((row, index) => {
      const subjectName = String(row.subjects?.name ?? "Subject");
      const ca = Number(row.ca_score ?? 0);
      const exam = Number(row.exam_score ?? 0);
      const score = Number(row.total_score ?? ca + exam);
      const [g, remark] = grade(score);
      doc.rect(42, y - 6, 511, 28).fill(index % 2 ? "#FFFFFF" : "#F8FAFC");
      doc.fillColor("#0F172A").fontSize(9).font("Helvetica").text(subjectName, columns[0] + 6, y);
      doc.text(String(ca), columns[1] + 6, y);
      doc.text(String(exam), columns[2] + 6, y);
      doc.font("Helvetica-Bold").text(String(score), columns[3] + 6, y);
      doc.text(String(row.grade ?? g), columns[4] + 6, y);
      doc.font("Helvetica").text(String(row.remark ?? remark), columns[5] + 6, y, { width: 120 });
      y += 28;
    });

    const commentsY = Math.max(y + 24, 560);
    doc.fillColor("#0F172A").fontSize(14).font("Helvetica-Bold").text("Comments", 42, commentsY);
    doc.roundedRect(42, commentsY + 22, 511, 86, 10).fillAndStroke("#F8FAFC", "#E2E8F0");
    doc.fillColor("#0F172A").fontSize(10).font("Helvetica-Bold").text("Class Teacher Comment", 58, commentsY + 36);
    doc.fillColor("#475569").fontSize(10).font("Helvetica").text(String(results[0]?.teacher_comment ?? "No teacher comment recorded."), 58, commentsY + 52, { width: 220 });
    doc.fillColor("#0F172A").fontSize(10).font("Helvetica-Bold").text("Principal Comment", 314, commentsY + 36);
    doc.fillColor("#475569").fontSize(10).font("Helvetica").text(String(results[0]?.principal_comment ?? "No principal comment recorded."), 314, commentsY + 52, { width: 210 });

    doc.fillColor("#64748B").fontSize(8).text(`Generated ${new Date().toLocaleString()} • This report is system generated.`, 42, 790, { align: "center", width: 511 });
    doc.end();

    const pdf = await new Promise<Buffer>((resolve) => doc.on("end", () => resolve(Buffer.concat(chunks))));
    return new NextResponse(new Uint8Array(pdf), {
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `inline; filename="report-card-${studentRow.admission_no}.pdf"`,
      },
    });
  } catch (error) {
    return apiError("GET /api/results/[student]/pdf", error);
  }
});
